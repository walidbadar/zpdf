static int hexv(char c)
{
	if (c >= '0' && c <= '9') {
		return c - '0';
	}
	if (c >= 'a' && c <= 'f') {
		return c - 'a' + 10;
	}
	if (c >= 'A' && c <= 'F') {
		return c - 'A' + 10;
	}
	return -1;
}

uint32_t pdf_glyph_to_unicode(const char *name)
{
	size_t n = strlen(name);

	if (n == 0) {
		return 0;
	}
	if (n == 1) {
		return (uint8_t)name[0];
	}
	/* uniXXXX / uXXXX[XX] */
	if (n >= 7 && memcmp(name, "uni", 3) == 0) {
		uint32_t v = 0;

		for (int i = 3; i < 7; i++) {
			int h = hexv(name[i]);

			if (h < 0) {
				v = 0;
				break;
			}
			v = (v << 4) | (uint32_t)h;
		}
		if (v) {
			return v;
		}
	}
	if (n >= 5 && n <= 7 && name[0] == 'u') {
		uint32_t v = 0;
		bool ok = true;

		for (size_t i = 1; i < n; i++) {
			int h = hexv(name[i]);

			if (h < 0) {
				ok = false;
				break;
			}
			v = (v << 4) | (uint32_t)h;
		}
		if (ok) {
			return v;
		}
	}
	for (size_t i = 0; i < sizeof(glyph_list) / sizeof(glyph_list[0]); i++) {
		if (strcmp(glyph_list[i].name, name) == 0) {
			return glyph_list[i].uni;
		}
	}
	/* "Aacute", "ccedilla", ... */
	for (size_t i = 0; i < sizeof(accents) / sizeof(accents[0]); i++) {
		size_t al = strlen(accents[i].accent);

		if (n == al + 1 && strcmp(name + 1, accents[i].accent) == 0) {
			uint16_t v = compose(name[0], (int)accents[i].combining);

			if (v) {
				return v;
			}
		}
	}
	/* "a.sc", "one.numr": take the part before the dot */
	const char *dot = strchr(name, '.');

	if (dot != NULL && dot != name) {
		char base[32];
		size_t bl = (size_t)(dot - name);

		if (bl < sizeof(base)) {
			memcpy(base, name, bl);
			base[bl] = 0;
			return pdf_glyph_to_unicode(base);
		}
	}
	return 0;
}
