void pdf_encoding_fill(enum pdf_base_encoding enc, uint16_t *table)
{
	for (int c = 0; c < 256; c++) {
		table[c] = 0;
	}
	for (int c = 0x20; c < 0x7F; c++) {
		table[c] = (uint16_t)c;
	}
	switch (enc) {
	case PDF_ENC_WINANSI:
		for (int c = 0x80; c < 0x100; c++) {
			table[c] = winansi_high[c - 0x80];
		}
		table[0xA0] = 0x00A0;
		table[0xAD] = 0x002D;
		break;
	case PDF_ENC_MACROMAN:
		for (int c = 0x80; c < 0x100; c++) {
			table[c] = macroman_high[c - 0x80];
		}
		break;
	case PDF_ENC_STANDARD:
		table[0x27] = 0x2019;
		table[0x60] = 0x2018;
		for (size_t i = 0; i < sizeof(standard_high) / sizeof(standard_high[0]); i++) {
			table[standard_high[i].code] = standard_high[i].uni;
		}
		break;
	}
}

