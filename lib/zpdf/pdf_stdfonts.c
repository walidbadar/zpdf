static bool has(const char *s, const char *sub)
{
	return strstr(s, sub) != NULL;
}

const uint16_t *pdf_std_font_widths(const char *base_font, int flags, bool *fixed)
{
	const char *n = base_font;
	const char *plus = strchr(n, '+');

	*fixed = false;
	if (plus != NULL && plus - n == 6) {
		n = plus + 1; /* subset prefix */
	}
	bool bold = has(n, "Bold") || has(n, "bold") || has(n, "Black") || has(n, "Heavy") ||
		    has(n, "Semibold") || ((flags & (1 << 18)) != 0);
	bool italic = has(n, "Italic") || has(n, "Oblique") || ((flags & (1 << 6)) != 0);

	if (has(n, "Courier") || has(n, "Mono") || (flags & 1)) {
		*fixed = true;
		return NULL;
	}
	if (has(n, "Times") || has(n, "Serif") || has(n, "Georgia") || has(n, "Book") ||
	    has(n, "Garamond") || has(n, "Roman") || ((flags & 2) && !has(n, "Arial") &&
	    !has(n, "Helvetica") && !has(n, "Verdana"))) {
		if (bold && italic) {
			return times_bolditalic;
		}
		if (bold) {
			return times_bold;
		}
		if (italic) {
			return times_italic;
		}
		return times_roman;
	}
	return bold ? helvetica_bold : helvetica;
}
